const assert=require('node:assert/strict');
const {Engine}=require('../engine.js');
const events=[],engine=new Engine(event=>events.push(event));
engine.start();
const s=engine.state;
const drop={id:'interaction-test',type:'wood',x:s.player.x+100};
s.drops.push(drop);
engine.interact(drop);
assert.ok(engine.walkTarget);
engine.interact({id:'unusable-tree',type:'tree',x:s.player.x+50});
assert.equal(engine.walkTarget,null,'a new rejected interaction cancels the old approach');
engine.interact(drop);
engine.keys.KeyA=true;
engine.update(.05);
assert.equal(engine.walkTarget,null,'manual movement cancels the approach');
engine.keys={};
// An empty outdoor click reaches interact(null); it stops only the queued walk.
engine.interact(drop);
engine.interact(null);
engine.update(.05);
assert.equal(engine.walkTarget,null,'empty ground cancels the approach');
assert.equal(s.player.moving,false);
engine.interact(drop);
engine.action={target:{type:'pet'},time:0,duration:2};
engine.interact(null);
assert.ok(engine.action,'empty ground does not cancel an active action');
assert.ok(engine.walkTarget,'active actions retain the existing command');
engine.action=null;
engine.attack={time:0,duration:1};
engine.interact(null);
assert.ok(engine.attack,'empty ground does not cancel an attack');
assert.ok(engine.walkTarget,'an active attack retains the existing command');
engine.attack=null;
engine.interact(drop);
s.drops=[];
engine.update(.05);
assert.equal(engine.walkTarget,null);
assert.ok(events.some(e=>e.type==='notice'&&e.text==='The target is no longer available.'));
// An id reused for a different type must not redirect the old command.
s.drops.push(drop);
engine.interact(drop);
s.drops=[{...drop,type:'stone'}];
const notices=events.filter(e=>e.type==='notice'&&e.text==='The target is no longer available.').length;
engine.update(.05);
assert.equal(engine.walkTarget,null,'a replacement of a different type is not the original target');
assert.equal(events.filter(e=>e.type==='notice'&&e.text==='The target is no longer available.').length,notices+1);
assert.equal(engine.action,null);
s.drops=[];
const before=s.inventory.wood;
s.drops.push(drop);
engine.interact(drop);
for(let i=0;i<100;i++)engine.update(.05);
assert.equal(s.inventory.wood,before+1,'arrival collects the target once');
assert.equal(s.drops.some(d=>d.id===drop.id),false);
assert.equal(engine.walkTarget,null);
console.log('interaction feedback tests passed');
